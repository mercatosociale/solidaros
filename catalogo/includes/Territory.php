/**
 * Territory page: [dirnet_territory]
 *  - without ?region=<slug>: index of the top-level locations (regions) with listing counts
 *  - region page (/<page>/<region>/): one card per directory type with its count, plus the map
 *  - type page (/<page>/<region>/<type>/): the list of that type in that region
 *
 * It sits on Directorist's [directorist_all_listing] shortcode (attributes
 * view, location, directory_type, map_height — verified in Directorist 8.10.4,
 * includes/model/Listings.php), so Directorist keeps doing map, cards and paging.
 *
 * Attributes: types="slug,slug" (directory type slugs; default: every type generated by a profile),
 *             by="type|category" (card grouping; visitors can switch),
 *             param="region" (query-string name), map_height="480", show="map|lists|both" (default both).
 */
class Territory {

	const PAGE_OPTION = 'dirnet_territory_page';

	public function boot() {
		add_shortcode( 'dirnet_territory', array( $this, 'shortcode' ) );
		add_action( 'init', array( __CLASS__, 'rename_page' ), 30 );
		add_action( 'init', array( __CLASS__, 'rename_slug' ), 31 );
		add_action( 'template_redirect', array( $this, 'old_redirect' ) );
		add_action( 'init', array( $this, 'rewrite' ), 32 );
		add_filter( 'query_vars', array( $this, 'query_vars' ) );
		add_filter( 'pre_get_document_title', array( $this, 'document_title' ), 20 );
		add_filter( 'redirect_canonical', array( $this, 'keep_url' ), 10, 2 );
	}

	/** One-time: the page called "Territory" / "Territorio" is now titled "Territories" / "Territori" (the address is left as it is). */
	public static function rename_page() {
		if ( get_option( 'dirnet_terr_renamed' ) ) {
			return;
		}
		$id = (int) get_option( self::PAGE_OPTION );
		$pg = $id ? get_post( $id ) : null;
		if ( $pg && in_array( $pg->post_title, array( 'Territorio', 'Territory' ), true ) ) {
			wp_update_post( array( 'ID' => $id, 'post_title' => __( 'Territories', 'directorist-network' ) ) );
		}
		update_option( 'dirnet_terr_renamed', 1, false );
	}

	/** One-time: the page address becomes /territori/ (old /territorio/... links are redirected). */
	public static function rename_slug() {
		if ( get_option( 'dirnet_terr_slug' ) ) {
			return;
		}
		$id = (int) get_option( self::PAGE_OPTION );
		$pg = $id ? get_post( $id ) : null;
		if ( $pg && in_array( $pg->post_name, array( 'territorio', 'territory' ), true ) ) {
			wp_update_post( array( 'ID' => $id, 'post_name' => 'territori' ) );
			update_option( 'dirnet_terr_oldslug', $pg->post_name, false );
		}
		update_option( 'dirnet_terr_slug', 1, false );
		update_option( 'dirnet_rewrite_ver', '', false );
	}

	public function old_redirect() {
		$old = get_option( 'dirnet_terr_oldslug' );
		if ( ! $old || ! is_404() ) {
			return;
		}
		$path = trim( (string) wp_parse_url( home_url( '/' ), PHP_URL_PATH ), '/' );
		$req  = trim( (string) wp_parse_url( isset( $_SERVER['REQUEST_URI'] ) ? wp_unslash( $_SERVER['REQUEST_URI'] ) : '', PHP_URL_PATH ), '/' );
		if ( $path && 0 === strpos( $req, $path . '/' ) ) {
			$req = substr( $req, strlen( $path ) + 1 );
		}
		if ( $req === $old || 0 === strpos( $req, $old . '/' ) ) {
			wp_safe_redirect( home_url( '/territori' . substr( $req, strlen( $old ) ) . '/' ), 301 );
			exit;
		}
	}

	/** Pretty region URLs: /<territory-page>/<region-slug>/ (the ?region= form keeps working). */
	public function rewrite() {
		$id = (int) get_option( self::PAGE_OPTION );
		if ( $id && get_post( $id ) ) {
			$uri = get_page_uri( $id );
			if ( $uri ) {
				add_rewrite_rule( '^' . preg_quote( $uri, '#' ) . '/([^/]+)/([^/]+)/?$', 'index.php?page_id=' . $id . '&dirnet_region=$matches[1]&dirnet_type=$matches[2]', 'top' );
				add_rewrite_rule( '^' . preg_quote( $uri, '#' ) . '/([^/]+)/?$', 'index.php?page_id=' . $id . '&dirnet_region=$matches[1]', 'top' );
			}
		}
	}

	public function query_vars( $vars ) {
		$vars[] = 'dirnet_region';
		$vars[] = 'dirnet_type';
		return $vars;
	}

	public function keep_url( $redirect, $requested ) {
		return get_query_var( 'dirnet_region' ) ? false : $redirect;
	}

	private static function current_term( $param ) {
		$slug = (string) get_query_var( 'dirnet_region' );
		if ( '' === $slug ) {
			foreach ( array( $param, 'regione' ) as $p ) {
				if ( isset( $_GET[ $p ] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
					$slug = wp_unslash( $_GET[ $p ] ); // phpcs:ignore WordPress.Security.NonceVerification
					break;
				}
			}
		}
		$slug = sanitize_title( $slug );
		return $slug ? get_term_by( 'slug', $slug, ATBDP_LOCATION ) : false;
	}

	public function document_title( $title ) {
		if ( is_page( (int) get_option( self::PAGE_OPTION ) ) ) {
			$t = self::current_term( 'region' );
			if ( $t ) {
				return $t->name . ' – ' . get_bloginfo( 'name' );
			}
		}
		return $title;
	}

	/** Published listings in a location, children included, optionally of one directory type. */
	private static function count( $term_id, $type_term_id = 0, $cat_term_id = 0 ) {
		$tax = array( array( 'taxonomy' => ATBDP_LOCATION, 'field' => 'term_id', 'terms' => (int) $term_id, 'include_children' => true ) );
		if ( $type_term_id ) {
			$tax[] = array( 'taxonomy' => 'atbdp_listing_types', 'field' => 'term_id', 'terms' => (int) $type_term_id );
		}
		if ( $cat_term_id ) {
			$tax[] = array( 'taxonomy' => ATBDP_CATEGORY, 'field' => 'term_id', 'terms' => (int) $cat_term_id, 'include_children' => true );
		}
		$q = new \WP_Query( array( 'post_type' => ATBDP_POST_TYPE, 'post_status' => 'publish', 'posts_per_page' => 1, 'fields' => 'ids', 'no_found_rows' => false, 'tax_query' => $tax ) ); // phpcs:ignore WordPress.DB.SlowDBQuery
		return (int) $q->found_posts;
	}

	private function region_url( $term, array $a, $type_slug = '' ) {
		$id = (int) get_option( self::PAGE_OPTION );
		if ( $id && get_option( 'permalink_structure' ) && get_page_uri( $id ) && 'region' === $a['param'] ) {
			return trailingslashit( get_permalink( $id ) ) . $term->slug . '/' . ( $type_slug ? $type_slug . '/' : '' );
		}
		$url = add_query_arg( $a['param'], $term->slug, get_permalink() );
		return $type_slug ? add_query_arg( 'tipo', $type_slug, $url ) : $url;
	}

	/** Shortcode entry: an error inside the plugin must not take the whole page down; admins see what failed. */
	public function shortcode( $atts ) {
		try {
			return $this->render( $atts );
		} catch ( \Throwable $e ) {
			error_log( '[directorist-network] dirnet_territory: ' . $e->getMessage() . ' in ' . $e->getFile() . ':' . $e->getLine() ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions
			return current_user_can( 'manage_options' ) ? '<pre style="white-space:pre-wrap;background:#fff3f3;border:1px solid #c00;padding:10px;font-size:12px">' . esc_html( 'Directorist Network [dirnet_territory]: ' . $e->getMessage() . ' — ' . basename( $e->getFile() ) . ':' . $e->getLine() ) . '</pre>' : '';
		}
	}

	private function render( $atts ) {
		if ( ! Generator::directorist_ready() || ! taxonomy_exists( ATBDP_LOCATION ) ) {
			return '';
		}
		$a = shortcode_atts( array( 'types' => '', 'param' => 'region', 'map_height' => '480', 'show' => 'both', 'by' => 'type' ), $atts, 'dirnet_territory' );

		$term = self::current_term( $a['param'] );
		if ( ! $term ) {
			return $this->index( $a );
		}

		$all   = self::type_slugs(); // directory-type term slug => name
		$types = $a['types'] ? array_map( 'sanitize_title', explode( ',', $a['types'] ) ) : array_keys( $all );
		$types = array_values( array_intersect( $types, array_keys( $all ) ) );
		$base  = get_permalink( (int) get_option( self::PAGE_OPTION ) );
		$base  = $base ? $base : remove_query_arg( array( $a['param'], 'regione', 'tipo' ) );

		$chosen = sanitize_title( (string) get_query_var( 'dirnet_type' ) );
		if ( '' === $chosen && isset( $_GET['tipo'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$chosen = sanitize_title( wp_unslash( $_GET['tipo'] ) ); // phpcs:ignore WordPress.Security.NonceVerification
		}
		$chosen = in_array( $chosen, $types, true ) ? $chosen : '';

		// Three filter rows: provinces (sub-territories), categories, types. Each tile narrows the list and the map.
		$rurl = $this->region_url( $term, $a );
		$prov = false;
		if ( isset( $_GET['prov'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$prov = get_term_by( 'slug', sanitize_title( wp_unslash( $_GET['prov'] ) ), ATBDP_LOCATION ); // phpcs:ignore WordPress.Security.NonceVerification
			$prov = ( $prov && (int) $prov->parent === (int) $term->term_id ) ? $prov : false;
		}
		$cat = false;
		if ( isset( $_GET['cat'] ) && taxonomy_exists( ATBDP_CATEGORY ) ) { // phpcs:ignore WordPress.Security.NonceVerification
			$cat = get_term_by( 'slug', sanitize_title( wp_unslash( $_GET['cat'] ) ), ATBDP_CATEGORY ); // phpcs:ignore WordPress.Security.NonceVerification
		}
		$loc    = $prov ? $prov : $term;
		$cat_id = $cat ? (int) $cat->term_id : 0;
		$state  = array( 'prov' => $prov ? $prov->slug : '', 'cat' => $cat ? $cat->slug : '', 'tipo' => $chosen );
		$url_of = function ( array $over ) use ( $state, $rurl ) {
			$q = array_filter( array_merge( $state, $over ), 'strlen' );
			return $q ? add_query_arg( $q, $rurl ) : $rurl;
		};

		$out  = '<div class="dirnet-territory"><p><a href="' . esc_url( $base ) . '">&larr; ' . esc_html__( 'All territories', 'directorist-network' ) . '</a>';
		if ( $prov || $cat || $chosen ) {
			$out .= ' &middot; <a href="' . esc_url( $rurl ) . '">' . esc_html( $term->name ) . '</a>';
		}
		$out .= '</p>';
		$title = $term->name . ( $prov ? ' – ' . $prov->name : '' ) . ( $cat ? ' – ' . $cat->name : '' ) . ( $chosen ? ' – ' . $all[ $chosen ] : '' );
		$out  .= '<h2>' . esc_html( $title ) . '</h2>';
		if ( ! $prov && ! $cat && ! $chosen && $term->description ) {
			$out .= '<div class="dirnet-territory-intro">' . wp_kses_post( wpautop( $term->description ) ) . '</div>';
		}
		$out .= '<style>' . Entities::tile_css() . '.dirnet-filterrow h3{margin:18px 0 0;font-size:1em}</style>';

		// Row 1: provinces.
		$cards = '';
		foreach ( self::filled( $term->term_id ) as $row ) {
			list( $c, $n ) = $row;
			$on     = $prov && (int) $prov->term_id === (int) $c->term_id;
			$cards .= self::card( $url_of( array( 'prov' => $on ? '' : $c->slug ) ), $n, $c->name, $c->slug, $on );
		}
		if ( $cards ) {
			$out .= '<div class="dirnet-filterrow"><h3>' . esc_html__( 'Provinces', 'directorist-network' ) . '</h3><div class="dirnet-type-cards">' . $cards . '</div></div>';
		}

		// Row 2: types.
		$cards = '';
		foreach ( $types as $ts ) {
			$tt = get_term_by( 'slug', $ts, 'atbdp_listing_types' );
			$n  = $tt ? self::count( $loc->term_id, $tt->term_id, $cat_id ) : 0;
			if ( ! $n ) {
				continue;
			}
			$on     = $ts === $chosen;
			$cards .= self::card( $url_of( array( 'tipo' => $on ? '' : $ts ) ), $n, $all[ $ts ], $ts, $on );
		}
		if ( $cards ) {
			$out .= '<div class="dirnet-filterrow"><h3>' . esc_html__( 'Types', 'directorist-network' ) . '</h3><div class="dirnet-type-cards">' . $cards . '</div></div>';
		}

		// Row 3: categories (top level, or the sub-categories of the chosen one).
		if ( taxonomy_exists( ATBDP_CATEGORY ) ) {
			$parent = 0;
			if ( $cat ) {
				$kids   = get_terms( array( 'taxonomy' => ATBDP_CATEGORY, 'parent' => $cat_id, 'hide_empty' => false, 'fields' => 'ids' ) );
				$parent = ( ! is_wp_error( $kids ) && $kids ) ? $cat_id : (int) $cat->parent;
			}
			$cats  = get_terms( array( 'taxonomy' => ATBDP_CATEGORY, 'parent' => $parent, 'hide_empty' => false ) );
			$cards = '';
			foreach ( is_wp_error( $cats ) ? array() : $cats as $c ) {
				$n = self::count( $loc->term_id, 0, $c->term_id );
				if ( ! $n ) {
					continue;
				}
				$on     = $cat && (int) $cat->term_id === (int) $c->term_id;
				$cards .= self::card( $url_of( array( 'cat' => $on ? ( $c->parent ? get_term( $c->parent, ATBDP_CATEGORY )->slug : '' ) : $c->slug ) ), $n, $c->name, $c->slug, $on );
			}
			if ( $cards ) {
				$out .= '<div class="dirnet-filterrow"><h3>' . esc_html__( 'Categories', 'directorist-network' ) . '</h3><div class="dirnet-type-cards">' . $cards . '</div></div>';
			}
		}

		$show     = $chosen ? array( $chosen ) : $types;
		$cat_attr = $cat ? ' category="' . esc_attr( $cat->slug ) . '"' : '';
		if ( in_array( $a['show'], array( 'map', 'both' ), true ) && $show ) {
			$out .= do_shortcode( '[dirnet_map location="' . esc_attr( $loc->slug ) . '" height="' . (int) $a['map_height'] . '" types="' . esc_attr( implode( ',', $show ) ) . '"' . $cat_attr . ']' ); // our own light map: Directorist's all-listing map loads every listing and can exhaust memory
		}
		if ( in_array( $a['show'], array( 'lists', 'both' ), true ) ) {
			$out .= do_shortcode( '[dirnet_entities filters="0" bar="1" tiles="0" types="' . esc_attr( implode( ',', $show ) ) . '" location="' . esc_attr( $loc->slug ) . '"' . $cat_attr . ']' );
		}
		return $out . '</div>';
	}

	/** Directory-type term slug => name, for the types generated by a profile. */
	private static function type_slugs() {
		$out = array();
		foreach ( Entities::types() as $slug => $t ) {
			$out[ $slug ] = $t['name'];
		}
		return $out;
	}

	private static function card( $url, $n, $label, $slug, $active ) {
		$hue = abs( crc32( $slug ) ) % 360; // stable colour; override with --dirnet-bg in the theme CSS
		return Entities::tile( $url, '', 'hsl(' . (int) $hue . ',45%,30%)', $label, '', 'dirnet-type-card', $active, (string) (int) $n );
	}

	/** If a territory called Italia (Italy) exists it is a territory like the others, listed first. */
	public static function national_first( array $terms ) {
		$first = array();
		$rest  = array();
		foreach ( $terms as $t ) {
			if ( is_object( $t ) && in_array( $t->slug, array( 'italia', 'italy' ), true ) ) {
				$first[] = $t;
			} else {
				$rest[] = $t;
			}
		}
		return array_merge( $first, $rest );
	}

	/** Territories (children of $parent) that have at least one published entity. */
	private static function filled( $parent ) {
		$out  = array();
		$list = get_terms( array( 'taxonomy' => ATBDP_LOCATION, 'parent' => (int) $parent, 'hide_empty' => false, 'orderby' => 'name' ) );
		if ( is_wp_error( $list ) ) {
			return $out;
		}
		foreach ( 0 === (int) $parent ? self::national_first( $list ) : $list as $t ) {
			$n = self::count( $t->term_id );
			if ( $n > 0 ) {
				$out[] = array( $t, $n );
			}
		}
		return $out;
	}

	private function index( array $a ) {
		$rows  = self::filled( 0 );
		$names = array_map( 'strtolower', array_map( 'trim', Territories::names() ) );
		if ( $names ) { // only Italy and the regions: other top-level terms (towns from imports) stay out
			$rows = array_values( array_filter( $rows, function ( $r ) use ( $names ) {
				return in_array( strtolower( trim( $r[0]->name ) ), $names, true ) || get_term_meta( $r[0]->term_id, '_dirnet_seeded', true );
			} ) );
		}
		// Italy always comes first, even when empty: red outline, no fill.
		$it = get_term_by( 'slug', 'italia', ATBDP_LOCATION );
		$it = $it ? $it : get_term_by( 'slug', 'italy', ATBDP_LOCATION );
		if ( ! $it ) {
			$tid = Territories::term( 'Italia', 0 );
			$it  = $tid ? get_term( $tid, ATBDP_LOCATION ) : false;
		}
		// No "Estero" tile: it is left out of the list.
		$rows = array_values( array_filter( $rows, function ( $r ) use ( $it ) {
			return ( ! $it || (int) $r[0]->term_id !== (int) $it->term_id ) && 'estero' !== $r[0]->slug;
		} ) );
		if ( $it && ! is_wp_error( $it ) ) {
			array_unshift( $rows, array( $it, self::count( $it->term_id ) ) );
		}
		$out = '<style>' . Entities::tile_css() . '.dirnet-sub{margin:28px 0 8px}.dirnet-terrs{grid-template-columns:repeat(5,minmax(0,1fr))}.dirnet-terrs .dirnet-tile{width:auto}.dirnet-tile.dirnet-italia{background:transparent!important;border:3px solid #000;color:#000!important;box-shadow:none}@media(max-width:900px){.dirnet-terrs{grid-template-columns:repeat(3,minmax(0,1fr))}}@media(max-width:560px){.dirnet-terrs{grid-template-columns:repeat(2,minmax(0,1fr))}}</style><div class="dirnet-terrs">';
		foreach ( $rows as $row ) {
			list( $t, $n ) = $row;
			$is_it = $it && (int) $t->term_id === (int) $it->term_id;
			$out  .= Entities::tile( $this->region_url( $t, $a ), '', 'hsl(' . (int) ( abs( crc32( $t->slug ) ) % 360 ) . ',45%,35%)', $t->name, (string) (int) $n, 'dirnet-terr' . ( $is_it ? ' dirnet-italia' : '' ) );
		}
		return $out . '</div>';
	}

	/** Create the territory page once (called after a profile is generated). */
	public static function ensure_page() {
		$id = (int) get_option( self::PAGE_OPTION );
		if ( $id && 'trash' !== get_post_status( $id ) && get_post( $id ) ) {
			return $id;
		}
		return 0; // pages are never created here: the site assigns them in System pages
	}
}
